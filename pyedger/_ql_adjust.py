def _stirlerr(n):
    n = np.asarray(n, dtype=np.float64)
    out = np.empty_like(n)
    with np.errstate(all="ignore"):
        small = n <= 15.0
        if np.any(small):
            ns = n[small]
            nn = ns + ns
            nn_int = np.trunc(nn)
            half = nn == nn_int
            o = np.empty_like(ns)
            o[half] = _SFERR_HALVES[nn_int[half].astype(np.int64)]
            nh = ns[~half]
            o[~half] = gammaln(nh + 1.0) - (nh + 0.5) * np.log(nh) + nh - _M_LN_SQRT_2PI
            out[small] = o
        big = ~small
        if np.any(big):
            nb = n[big]
            nn = nb * nb
            o = ((_S0 - (_S1 - (_S2 - (_S3 - _S4 / nn) / nn) / nn) / nn) / nb)
            k = nb > 35
            o[k] = ((_S0 - (_S1 - (_S2 - _S3 / nn[k]) / nn[k]) / nn[k]) / nb[k])
            k = nb > 80
            o[k] = ((_S0 - (_S1 - _S2 / nn[k]) / nn[k]) / nb[k])
            k = nb > 500
            o[k] = ((_S0 - _S1 / nn[k]) / nb[k])
            out[big] = o
    return out


def _bd0(x, np_):
    x = np.asarray(x, dtype=np.float64)
    np_ = np.asarray(np_, dtype=np.float64)
    with np.errstate(all="ignore"):
        near = np.abs(x - np_) < 0.1 * (x + np_)
        out = np.empty_like(x)
        far = ~near
        out[far] = x[far] * np.log(x[far] / np_[far]) + np_[far] - x[far]
        idx = np.nonzero(near)[0]
        if idx.size:
            xs = x[idx]
            v = (xs - np_[idx]) / (xs + np_[idx])
            s = (xs - np_[idx]) * v
            res = np.empty_like(s)
            done = np.abs(s) < np.finfo(np.float64).tiny
            res[done] = s[done]
            ej = 2 * xs * v
            v = v * v
            active = ~done
            for j in range(1, 1000):
                if not active.any():
                    break
                ej = np.where(active, ej * v, ej)
                s1 = s + ej / ((j << 1) + 1)
                conv = active & (s1 == s)
                res[conv] = s1[conv]
                active &= ~conv
                s = np.where(active, s1, s)
            if active.any():  # fell through the 1000-term loop (never in practice)
                xa = xs[active]
                res[active] = xa * np.log(xa / np_[idx][active]) + np_[idx][active] - xa
            out[idx] = res
    return out


def _dbinom_raw(x, n, p, q):
    x, n, p, q = (np.asarray(a, dtype=np.float64) for a in (x, n, p, q))
    out = np.zeros_like(x)
    with np.errstate(all="ignore"):
        code = _select([p == 0, q == 0, x == 0, x == n, (x < 0) | (x > n)], x.size)
        k = code == 0; out[k] = np.where(x[k] == 0, 1.0, 0.0)
        k = code == 1; out[k] = np.where(x[k] == n[k], 1.0, 0.0)
        k = np.nonzero(code == 2)[0]
        if k.size:
            nk, pk, qk = n[k], p[k], q[k]
            lc = np.where(pk < 0.1, -_bd0(nk, nk * qk) - nk * pk, nk * np.log(qk))
            out[k] = np.where(nk == 0, 1.0, np.exp(lc))
        k = np.nonzero(code == 3)[0]
        if k.size:
            nk, pk, qk = n[k], p[k], q[k]
            lc = np.where(qk < 0.1, -_bd0(nk, nk * pk) - nk * qk, nk * np.log(pk))
            out[k] = np.exp(lc)
        k = np.nonzero(code == 5)[0]
        if k.size:
            xk, nk, pk, qk = x[k], n[k], p[k], q[k]
            lc = _stirlerr(nk) - _stirlerr(xk) - _stirlerr(nk - xk) - _bd0(xk, nk * pk) - _bd0(nk - xk, nk * qk)
            lf = _M_LN_2PI + np.log(xk) + np.log1p(-xk / nk)
            out[k] = np.exp(lc - 0.5 * lf)
    return out


def _dnbinom_mu(x, size, mu):
    """R's dnbinom_mu(x, size, mu, log=FALSE) for scalar integer x >= 0 and array size, mu."""
    size = np.asarray(size, dtype=np.float64)
    mu = np.asarray(mu, dtype=np.float64)
    with np.errstate(all="ignore"):
        if x == 0:
            return np.exp(size * np.where(size < mu, np.log(size / (size + mu)), np.log1p(-mu / (size + mu))))
        out = np.empty_like(size)
        tiny = x < 1e-10 * size
        if np.any(tiny):
            sz, m = size[tiny], mu[tiny]
            p = np.where(sz < m, np.log(sz / (1 + sz / m)), np.log(m / (1 + m / sz)))
            out[tiny] = np.exp(x * p - m - gammaln(x + 1.0) + np.log1p(x * (x - 1) / (2 * sz)))
        k = ~tiny
        if np.any(k):
            sz, m = size[k], mu[k]
            p = sz / (sz + x)
            ans = _dbinom_raw(sz, x + sz, sz / (sz + m), m / (sz + m))
            out[k] = p * ans
    return out


def _exact_nb_weights(mu, phi):
    """compute_weight branch phi >= 4 (exact truncated sums). mu >= low_bound assumed."""
    with np.errstate(all="ignore"):
        v = mu * mu * phi + 10
        # C: int n = v; values beyond INT_MAX crash R (negative VLA).  Cap at 50.
        big = ~(v < 50)  # includes NaN
        n = np.where(big, 50, np.trunc(np.where(big, 0, v))).astype(np.int64)
        size = 1 / phi
        nmax = int(n.max()) if n.size else 0
        pr0 = _dnbinom_mu(0, size, mu)
        de0 = 2 * (-size * np.log(size / (mu + size)))
        dd = pr0 * de0
        prs = [pr0]
        des = [de0]
        for i in range(1, nmax):
            pri = _dnbinom_mu(i, size, mu)
            dei = 2 * (i * np.log(i / mu) - (i + size) * np.log((i + size) / (mu + size)))
            prs.append(pri)
            des.append(dei)
            act = i < n
            dd = np.where(act, dd + pri * dei, dd)
        out = np.zeros_like(mu)
        for i in range(nmax):
            act = i < n
            d = des[i] - dd
            out = np.where(act, out + prs[i] * d * d, out)
        return 2 * dd / out, 2 * dd * dd / out


def compute_weight(u, phi, prior=1.0):
    """Vectorised port of ``compute_weight(u, phi, prior, wpt)``.

    ``u`` and ``phi`` are broadcast together; returns ``(alpha, kappa)`` arrays
    (wpt[0] = deviance weight, wpt[1] = df weight).
    """
    u, phi, prior = np.broadcast_arrays(np.asarray(u, dtype=np.float64), np.asarray(phi, dtype=np.float64),
                                        np.asarray(prior, dtype=np.float64))
    shape = u.shape
    u = u.ravel()
    phi = phi.ravel()
    with np.errstate(all="ignore"):
        mu = u / prior.ravel()
    a = np.zeros_like(mu)
    k = np.zeros_like(mu)
    code = _select([phi < 0.736, phi < 4.001], mu.size)       # edgeR >= 4.4 (4.0: phi < 4.0)
    s = np.nonzero(code == 0)[0]
    if s.size:
        a[s] = _nbdevc_1(mu[s], phi[s], kappa=False)
        k[s] = _nbdevc_1(mu[s], phi[s], kappa=True)
    s = np.nonzero(code == 1)[0]
    if s.size:
        a[s] = _nbdevc_2(mu[s], phi[s], kappa=False)
        k[s] = _nbdevc_2(mu[s], phi[s], kappa=True)
    s = np.nonzero((code == 2) & ~(mu < _LOW_BOUND))[0]
    if s.size:
        a[s], k[s] = _exact_nb_weights(mu[s], phi[s])
    return a.reshape(shape), k.reshape(shape)


def unit_nb_deviance(y, mu, phi):
    """Vectorised port of ``compute_unit_nb_deviance`` (src/nbdev.c)."""
    y, mu, phi = np.broadcast_arrays(*(np.asarray(a, dtype=np.float64) for a in (y, mu, phi)))
    y = y + 1e-8
    mu = mu + 1e-8
    out = np.empty(y.shape, dtype=np.float64)
    with np.errstate(all="ignore"):
        pois = phi < 1e-4
        resid = y[pois] - mu[pois]
        yp, ph = y[pois], phi[pois]
        # NB: C's ``2/3*resid`` is integer division -> 0*resid
        out[pois] = 2 * (yp * _log(yp / mu[pois]) - resid - 0.5 * resid * resid * ph * (1 + ph * (0.0 * resid - yp)))
        nb = ~pois
        yn, mn, pn = y[nb], mu[nb], phi[nb]
        product = mn * pn
        gam = product > 1e6
        o = np.empty_like(yn)
        g_y, g_m, g_p = yn[gam], mn[gam], product[gam]
        o[gam] = 2 * ((g_y - g_m) / g_m - _log(g_y / g_m)) * g_m / (1 + g_p)
        r = ~gam
        r_y, r_m = yn[r], mn[r]
        invphi = 1 / pn[r]
        o[r] = 2 * (r_y * _log(r_y / r_m) + (r_y + invphi) * _log((r_m + invphi) / (r_y + invphi)))
        out[nb] = o
    return np.maximum(out, 0.0)                    # edgeR >= 4.4: fmax2(out, 0)


