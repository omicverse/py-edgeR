def _select(conds, n):
    """Branch index of an if / else-if chain (first true condition; default len(conds))."""
    code = np.full(n, len(conds), dtype=np.int64)
    undecided = np.ones(n, dtype=bool)
    for k, c in enumerate(conds):
        hit = undecided & c
        code[hit] = k
        undecided &= ~hit
    return code


# Chebyshev evaluators.  ``it`` (the C ``iter`` offset) is a Python int: every branch is
# evaluated separately on its own subset, so coefficients are scalars.  The arithmetic
# (operand order and summation order) follows the C source exactly.
def _cheb_1d(W, it, t, m):
    """out = W[it] + W[it+1]*t;  for i in 2..m-1: T_i = 2*t*T_{i-1} - T_{i-2}; out += W[it+i]*T_i."""
    t0 = np.ones_like(t)
    t1 = t
    out = W[it] + W[it + 1] * t
    for i in range(2, m):
        t2 = 2 * t * t1 - t0
        out = out + W[it + i] * t2
        t0, t1 = t1, t2
    return out


def _cheb_list(t, m):
    T = [np.ones_like(t), t]
    for i in range(2, m):
        T.append(2 * t * T[i - 1] - T[i - 2])
    return T


def _cheb_2d(W, it, x, y, m):
    """for i (y) in 0..m-1: for j (x) in 0..m-1: out += W[iter++]*xc[j]*yc[i]   (out starts at 0)."""
    xc = _cheb_list(x, m)
    yc = _cheb_list(y, m)
    out = np.zeros_like(x)
    tmp = np.empty_like(x)
    k = it
    for i in range(m):
        for j in range(m):
            np.multiply(xc[j], W[k], out=tmp)  # (W[k]*xc[j])
            tmp *= yc[i]                       # *yc[i]
            out += tmp
            k += 1
    return out


def _cheb_mix(W, it, x, y, m, off2, off3):
    """w1/w2/w3 scheme used for intermediate mu ranges."""
    w1 = W[it] + W[it + 1] * y
    w2 = W[it + off2] + W[it + off2 + 1] * y
    w3 = W[it + off3] + W[it + off3 + 1] * x
    x0 = np.ones_like(x)
    x1 = x
    y0 = np.ones_like(y)
    y1 = y
    for i in range(2, m):
        x2 = 2 * x * x1 - x0
        y2 = 2 * y * y1 - y0
        w1 = w1 + W[it + i] * y2
        w2 = w2 + W[it + off2 + i] * y2
        w3 = w3 + W[it + off3 + i] * x2
        x0, x1 = x1, x2
        y0, y1 = y1, y2
    return w1, w2, w3


def _run_chain(m, spec, default_last=True):
    """Yield (branch_number, index_array) for an if/else-if chain on ``m``.

    ``spec`` is a list of upper bounds ``b`` meaning ``if (m < b)``; with
    ``default_last`` the final else-branch gets number ``len(spec)``.
    """
    code = _select([m < b for b in spec], m.size)
    nb = len(spec) + (1 if default_last else 0)
    for k in range(nb):
        idx = np.nonzero(code == k)[0]
        if idx.size:
            yield k, idx


