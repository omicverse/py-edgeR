# --------------------------------------------------------------------------------------
# libm-exact elementwise transcendental functions
# --------------------------------------------------------------------------------------
# NumPy's SIMD np.log / np.exp differ from the platform libm (which R and edgeR's C code
# call) in ~0.4% of arguments by 1 ulp.  Because the NB unit deviance suffers from
# catastrophic cancellation when y ~ mu, such 1-ulp differences can grow to ~1e-8 relative
# in individual unit deviances.  Routing positive finite arguments through Python's
# ``math`` module (a thin wrapper around the same C libm) removes that source of
# discrepancy at a cost of ~0.1 us per element.
def _libm_map(fn, v, ok):
    idx = np.nonzero(ok.ravel())[0]
    out = np.empty(idx.size, dtype=np.float64)
    if idx.size:
        out[:] = np.fromiter(map(fn, v.ravel()[idx].tolist()), dtype=np.float64, count=idx.size)
    return idx, out


def _log(v):
    v = np.asarray(v, dtype=np.float64)
    with np.errstate(all="ignore"):
        res = np.array(np.log(v), dtype=np.float64)
    idx, vals = _libm_map(math.log, v, (v > 0) & np.isfinite(v))
    res.reshape(-1)[idx] = vals
    return res


def _log1p(v):
    v = np.asarray(v, dtype=np.float64)
    with np.errstate(all="ignore"):
        res = np.array(np.log1p(v), dtype=np.float64)
    idx, vals = _libm_map(math.log1p, v, (v > -1) & np.isfinite(v))
    res.reshape(-1)[idx] = vals
    return res


def _exp(v):
    v = np.asarray(v, dtype=np.float64)
    with np.errstate(all="ignore"):
        res = np.array(np.exp(v), dtype=np.float64)
    idx, vals = _libm_map(math.exp, v, np.isfinite(v) & (v < 709.0))
    res.reshape(-1)[idx] = vals
    return res

