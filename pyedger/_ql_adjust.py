def _nrm2(v, axis=-1):
    """Euclidean norm; rescaled (as BLAS dnrm2 does) only where under/overflow threatens."""
    v = np.asarray(v, dtype=np.float64)
    with np.errstate(all="ignore"):
        r = np.sqrt(np.sum(v * v, axis=axis))
        bad = ~((r > 1e-150) & (r < 1e150))
        if np.any(bad):
            a = np.abs(v)
            scale = np.max(a, axis=axis, keepdims=True)
            safe = np.where(scale > 0, scale, 1.0)
            rs = np.sqrt(np.sum((a / safe) ** 2, axis=axis)) * np.squeeze(scale, axis=axis)
            rs = np.where(np.squeeze(scale, axis=axis) > 0, rs, 0.0)
            r = np.where(bad, rs, r)
    return r


def _dqrdc2_single(x, tol=_QR_TOL):
    """Literal port of LINPACK dqrdc2 for one n x p matrix (copied). Returns x, qraux, k, jpvt."""
    x = np.array(x, dtype=np.float64, order="F", copy=True)
    n, p = x.shape
    qraux = np.array([_nrm2(x[:, j]) for j in range(p)], dtype=np.float64)
    work1 = qraux.copy()
    work2 = qraux.copy()
    work2[work2 == 0.0] = 1.0
    jpvt = np.arange(1, p + 1)
    lup = min(n, p)
    k = p + 1
    for l in range(lup):  # 0-based l; Fortran l+1
        # cycle negligible columns to the end (limited pivoting)
        while not ((l + 1) >= k or qraux[l] >= work2[l] * tol):
            col = x[:, l].copy()
            x[:, l:p - 1] = x[:, l + 1:p]
            x[:, p - 1] = col
            i, t, tt, ttt = jpvt[l], qraux[l], work1[l], work2[l]
            jpvt[l:p - 1] = jpvt[l + 1:p].copy()
            qraux[l:p - 1] = qraux[l + 1:p].copy()
            work1[l:p - 1] = work1[l + 1:p].copy()
            work2[l:p - 1] = work2[l + 1:p].copy()
            jpvt[p - 1], qraux[p - 1], work1[p - 1], work2[p - 1] = i, t, tt, ttt
            k -= 1
        if l + 1 == n:
            continue
        nrmxl = float(_nrm2(x[l:, l]))
        if nrmxl == 0.0:
            continue
        if x[l, l] != 0.0:
            nrmxl = math.copysign(nrmxl, x[l, l])
        x[l:, l] *= 1.0 / nrmxl
        x[l, l] = 1.0 + x[l, l]
        for j in range(l + 1, p):
            t = -float(np.dot(x[l:, l], x[l:, j])) / x[l, l]
            x[l:, j] += t * x[l:, l]
            if qraux[j] == 0.0:
                continue
            tt = 1.0 - (abs(x[l, j]) / qraux[j]) ** 2
            tt = max(tt, 0.0)
            t = tt
            if abs(t) < 1e-6:
                qraux[j] = _nrm2(x[l + 1:, j])
                work1[j] = qraux[j]
            else:
                qraux[j] = qraux[j] * math.sqrt(t)
        qraux[l] = x[l, l]
        x[l, l] = -nrmxl
    k = min(k - 1, n)
    return x, qraux, k, jpvt


def _hat_single(xw):
    """QR_hat for one weighted design (dqrdc2 + dqrqy on the first k = rank columns)."""
    n, p = xw.shape
    x, qraux, k, _ = _dqrdc2_single(xw)
    Y = np.zeros((n, k))
    for i in range(k):
        Y[i, i] = 1.0
    ju = min(k, n - 1)
    for j in range(ju - 1, -1, -1):  # dqrsl: apply H_ju ... H_1
        if qraux[j] == 0.0:
            continue
        v = x[j:, j].copy()
        v[0] = qraux[j]
        t = -(v @ Y[j:, :]) / v[0]
        Y[j:, :] += np.outer(v, t)
    hat = np.zeros(n)
    for j in range(k):
        hat += Y[:, j] * Y[:, j]
    return hat


def _hat_chunk(x, tol):
    """Batched dqrdc2 without pivoting on x of shape (n, p, G) (modified in place).

    Returns hat (n, G) and a mask of genes for which dqrdc2 would pivot (those are
    recomputed exactly by the caller).
    """
    n, p, G = x.shape
    qraux = _nrm2(x, axis=0)  # (p, G)
    work2 = np.where(qraux == 0.0, 1.0, qraux)
    pivot = np.zeros(G, dtype=bool)
    lup = min(n, p)
    for l in range(lup):
        # with no previous pivot k == p+1 > l, so dqrdc2 pivots iff this test fails
        pivot |= ~(qraux[l] >= work2[l] * tol)
        if l + 1 == n:
            continue
        xl = x[l:, l, :]  # (n-l, G)
        nrmxl = _nrm2(xl, axis=0)
        zero = nrmxl == 0.0
        pivot |= zero  # impossible without a pivot; routed to the exact path anyway
        nrmxl = np.where(xl[0] != 0.0, np.copysign(nrmxl, xl[0]), nrmxl)
        xl = xl * (1.0 / np.where(zero, 1.0, nrmxl))
        xl[0] = 1.0 + xl[0]
        x[l:, l, :] = xl
        if l + 1 < p:
            xr = x[l:, l + 1:, :]  # (n-l, p-l-1, G) view
            t = -np.sum(xl[:, None, :] * xr, axis=0) / xl[0]  # ddot (sequential over rows)
            xr += xl[:, None, :] * t[None, :, :]  # daxpy
            q = qraux[l + 1:]
            qz = q == 0.0
            tt = 1.0 - (np.abs(xr[0]) / np.where(qz, 1.0, q)) ** 2
            tt = np.maximum(tt, 0.0)
            recompute = (np.abs(tt) < 1e-6) & ~qz
            newq = np.where(qz, q, q * np.sqrt(tt))
            if recompute.any():
                newq = np.where(recompute, _nrm2(xr[1:], axis=0), newq)
            qraux[l + 1:] = newq
        qraux[l] = np.where(zero, qraux[l], xl[0])
        x[l, l, :] = np.where(zero, x[l, l, :], -nrmxl)

    # dqrqy with k = min(p, n) columns: Y = H_1 ... H_ju [I_k; 0]
    k = min(p, n)
    Y = np.zeros((n, k, G))
    for i in range(k):
        Y[i, i, :] = 1.0
    ju = min(k, n - 1)
    for j in range(ju - 1, -1, -1):
        v = x[j:, j, :].copy()
        v[0] = qraux[j]
        # columns < j of Y are exactly zero in rows >= j, so H_j leaves them unchanged
        Yj = Y[j:, j:, :]
        t = -np.sum(v[:, None, :] * Yj, axis=0) / v[0]
        Yj += v[:, None, :] * t[None, :, :]
    hat = np.zeros((n, G))
    for j in range(k):
        hat += Y[:, j, :] * Y[:, j, :]
    return hat, pivot


def _hat_values(xw, tol=_QR_TOL, chunk=4096):
    """Hat values of each weighted design xw[g] (shape (G, n, p)) as edgeR's QR_hat."""
    G, n, p = xw.shape
    hat = np.empty((G, n))
    pivot = np.zeros(G, dtype=bool)
    with np.errstate(all="ignore"):
        for s in range(0, G, chunk):
            e = min(G, s + chunk)
            x = np.ascontiguousarray(np.transpose(xw[s:e], (1, 2, 0)))
            h, pv = _hat_chunk(x, tol)
            hat[s:e] = h.T
            pivot[s:e] = pv
        for g in np.nonzero(pivot)[0]:
            hat[g] = _hat_single(xw[g])
    return hat, pivot


