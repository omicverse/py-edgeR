def _seqsum(v):
    """Left-to-right sum (the C loop's rounding order)."""
    return float(np.cumsum(v)[-1]) if v.size else 0.0


def _lowest(x, y, n, xs, nleft, nright, w, userw, rw):
    """R clowess helper ``lowest`` (1-based nleft/nright), vectorised.

    Sums use cumulative (sequential) summation so rounding matches the C loop.
    The ``w`` workspace is not needed by callers and is left untouched.
    """
    rng = x[n - 1] - x[0]
    h = max(xs - x[nleft - 1], x[nright - 1] - xs)
    h9 = 0.999 * h
    h1 = 0.001 * h
    xx = x[nleft - 1:]
    r = np.abs(xx - xs)
    stop = np.flatnonzero((r > h9) & (xx > xs))
    m = stop[0] if stop.size else xx.size          # entries j = nleft .. nrt
    xx, r = xx[:m], r[:m]
    q = r / h if h != 0 else np.zeros_like(r)
    q = 1.0 - q * q * q
    ww = np.where(r <= h1, 1.0, q * q * q)
    inside = r <= h9
    ww = np.where(inside, ww, 0.0)
    if userw:
        ww = np.where(inside, ww * rw[nleft - 1:nleft - 1 + m], 0.0)
    a = _seqsum(np.where(inside, ww, 0.0))
    if a <= 0.0:
        return None
    ww = ww / a
    if h > 0.0:
        a = _seqsum(ww * xx)
        b = xs - a
        d = xx - a
        c = _seqsum(ww * (d * d))                  # w[j]*fsquare(x[j]-a)
        if np.sqrt(c) > 0.001 * rng:
            b /= c
            ww = ww * (b * d + 1.0)
    return _seqsum(ww * y[nleft - 1:nleft - 1 + m])


def _clowess(x, y, f, nsteps, delta):
    n = len(x)
    x = np.asarray(x, dtype=np.float64)
    y = np.asarray(y, dtype=np.float64)
    ys = [0.0] * n
    if n < 2:
        return np.array([y[0]])
    rw = [0.0] * n
    res = [0.0] * n
    ns = max(2, min(n, int(f * n + 1e-7)))
    it = 1
    while it <= nsteps + 1:
        nleft = 1
        nright = ns
        last = 0
        i = 1
        while True:
            if nright < n:
                d1 = x[i - 1] - x[nleft - 1]
                d2 = x[nright] - x[i - 1]
                if d1 > d2:
                    nleft += 1
                    nright += 1
                    continue
            v = _lowest(x, y, n, x[i - 1], nleft, nright, res, it > 1, rw)
            ys[i - 1] = y[i - 1] if v is None else v
            if last < i - 1:
                denom = x[i - 1] - x[last - 1]
                for j in range(last + 1, i):
                    alpha = (x[j - 1] - x[last - 1]) / denom
                    ys[j - 1] = alpha * ys[i - 1] + (1.0 - alpha) * ys[last - 1]
            last = i
            cut = x[last - 1] + delta
            i = last + 1
            while i <= n:
                if x[i - 1] > cut:
                    break
                if x[i - 1] == x[last - 1]:
                    ys[i - 1] = ys[last - 1]
                    last = i
                i += 1
            i = max(last + 1, i - 1)
            if last >= n:
                break
        for k in range(n):
            res[k] = y[k] - ys[k]
        sc = 0.0
        for k in range(n):
            sc += abs(res[k])
        sc /= n
        if it > nsteps:
            break
        rw = np.abs(np.asarray(res, dtype=np.float64))
        srt = np.sort(rw)
        m1 = n // 2
        if n % 2 == 0:
            m2 = n - m1 - 1
            cmad = 3.0 * (srt[m1] + srt[m2])
        else:
            cmad = 6.0 * srt[m1]
        if cmad < 1e-7 * sc:
            break
        c9 = 0.999 * cmad
        c1 = 0.001 * cmad
        r = np.abs(np.asarray(res, dtype=np.float64))
        q = 1.0 - (r / cmad) * (r / cmad)
        rw = np.where(r <= c1, 1.0, np.where(r <= c9, q * q, 0.0))
        it += 1
    return np.array(ys)


def r_lowess(x, y, f=2.0 / 3.0, iter=3, delta=None):
    """Exact port of R's ``stats::lowess`` (returns sorted x and fitted y)."""
    x = np.asarray(x, dtype=np.float64)
    y = np.asarray(y, dtype=np.float64)
    if delta is None:
        delta = 0.01 * (np.max(x) - np.min(x))
    o = np.argsort(x, kind="stable")
    xs = x[o]
    return xs, _clowess(xs, y[o], float(f), int(iter), float(delta))


def _r_quantile7(x, prob):
    x = np.sort(np.asarray(x, dtype=np.float64))
    n = x.size
    index = 1 + max(n - 1, 0) * prob
    lo = int(np.floor(index))
    hi = int(np.ceil(index))
    qs = x[lo - 1]
    if index > lo and x[hi - 1] != qs:
        h = index - lo
        qs = (1 - h) * qs + h * x[hi - 1]
    return qs


def _rsort_with_index(x):
    """Order produced by R's ``rsort_with_index`` (Shell sort; not stable for ties)."""
    x = np.asarray(x, dtype=np.float64)
    o = np.argsort(x, kind="stable")
    xs = x[o]
    if xs.size < 2 or not np.any(xs[1:] == xs[:-1]):
        return o                                 # no ties: every sort gives the same order
    xl = x.tolist()
    idx = list(range(len(xl)))
    n = len(xl)
    h = 1
    while h <= n // 9:
        h = 3 * h + 1
    while h > 0:
        for i in range(h, n):
            v, iv = xl[i], idx[i]
            j = i
            while j >= h and xl[j - h] > v:
                xl[j] = xl[j - h]
                idx[j] = idx[j - h]
                j -= h
            xl[j] = v
            idx[j] = iv
        h //= 3
    return np.asarray(idx)


def compute_prior(ave_log_cpm, s2, df):
    """edgeR 4.10 ``compute_prior`` (src/ql_glm.c): average quasi-dispersion.

    Lowess (f = 0.5, iter = 3) of s2^(1/4) on AveLogCPM over genes with
    df > 1e-8, 90% quantile (type 7) of the fitted trend, floored at 1, ^4.
    """
    ag = np.asarray(ave_log_cpm, dtype=np.float64)
    s2 = np.asarray(s2, dtype=np.float64)
    df = np.asarray(df, dtype=np.float64)
    keep = df > 1e-8
    xx = ag[keep]
    yy = np.sqrt(np.sqrt(s2[keep]))
    k = xx.size
    o = _rsort_with_index(xx)
    xs, ys = xx[o], yy[o]
    delta = 0.01 * (xs[k - 1] - xs[0])
    ans = np.sort(_clowess(xs, ys, 0.5, 3, delta))
    m = (k - 1) * 0.9
    lo = int(m)
    h = m - lo
    p = (1 - h) * ans[lo] + h * ans[min(lo + 1, k - 1)]
    if p < 1.0:
        p = 1.0
    return p * p * p * p
